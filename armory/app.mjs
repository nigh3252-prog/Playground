function toast(message) { $("toast").textContent=message;$("toast").hidden=false;clearTimeout(toastTimer);toastTimer=setTimeout(()=>$("toast").hidden=true,4300); }
function persist() {
  try { localStorage.setItem(storageKey,JSON.stringify({favorites:[...favorites],notes,orientations})); }
  catch { if(storageAvailable) toast("Browser storage is unavailable. Export JSON to keep your favorites.");storageAvailable=false; }
}
function restore() {
  try {
    const data=JSON.parse(localStorage.getItem(storageKey)||"{}");
    favorites=new Set(Array.isArray(data.favorites)?data.favorites.filter(id=>byId.has(id)):[]);
    notes={};orientations={};
    for (const id of favorites) {
      if(typeof data.notes?.[id]==="string") notes[id]=data.notes[id].slice(0,4000);
      const r=data.orientations?.[id];
      if(Array.isArray(r)&&r.length===3&&r.every(n=>Number.isFinite(n)&&Math.abs(n)<1000)) orientations[id]=r;
    }
  } catch { favorites=new Set();notes={};orientations={};toast("Saved data could not be read. Import a JSON backup if you have one."); }
}
function updateFavoriteButtons() {
  $("favorite-count").textContent=favorites.size;
  $("export-open").disabled=favorites.size===0;
  $("favorites-filter").setAttribute("aria-pressed",String(onlyFavorites));
  const on=current && favorites.has(current.id);
  $("model-favorite").textContent=on?"★":"☆";
  $("model-favorite").setAttribute("aria-pressed",String(!!on));
  $("model-favorite").setAttribute("aria-label",on?"Remove current weapon from favorites":"Add current weapon to favorites");
  document.querySelectorAll(".card-star").forEach(button=>{
    const selected=favorites.has(button.dataset.id);
    button.textContent=selected?"★":"☆";button.setAttribute("aria-pressed",String(selected));
    button.setAttribute("aria-label",(selected?"Remove ":"Favorite ")+byId.get(button.dataset.id).name);
  });
}
function toggleFavorite(id) {
  if(!byId.has(id)) return;
  const removed=favorites.has(id);
  if(removed) favorites.delete(id);else favorites.add(id);
  persist();updateFavoriteButtons();
  if(onlyFavorites) renderCatalog();
  toast(removed?"Removed from favorites":"Saved to favorites");
}
function packById(id) { return catalog.packs.find(p=>p.id===id); }
function applyFilters() {
  const pack=$("pack").value,era=$("era").value,q=$("search").value.trim().toLowerCase();
  return models.filter(m=>(pack==="all"||m.pack===pack)&&(era==="all"||m.era.includes(era))&&(!onlyFavorites||favorites.has(m.id))&&(!q||[m.name,m.creator,m.description,...m.era,packById(m.pack).name].join(" ").toLowerCase().includes(q)));
}
