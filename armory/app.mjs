async function exportZip() {
  if(exportBusy) return;
  const selected=selectedModels();if(!selected.length) return;
  const selection=selectionManifest(selected,notes,orientations);
  exportBusy=true;$("import-json").disabled=true;renderFavorites();
  try {
    const entries=[];
    for(let i=0;i<selected.length;i++) {
      const model=selected[i];$("export-status").textContent="Packing "+(i+1)+" / "+selected.length+" · "+model.name;
      const response=await fetch(model.file);if(!response.ok) throw new Error("Could not download "+model.name+".");
      const bytes=new Uint8Array(await response.arrayBuffer());
      if(bytes.length!==model.bytes) throw new Error("File size check failed for "+model.name+".");
      if(globalThis.crypto?.subtle) {
        const digest=new Uint8Array(await crypto.subtle.digest("SHA-256",bytes));
        const hash=Array.from(digest,b=>b.toString(16).padStart(2,"0")).join("");
        if(hash!==model.sha256) throw new Error("File integrity check failed for "+model.name+".");
      }
      entries.push({name:"models/"+model.id+".glb",data:bytes});
    }
    const credits=selected.map(m=>[m.name+" — "+m.creator,m.license+" · "+m.licenseUrl,"Source: "+m.source,"License listing: "+m.licenseEvidence,"Download source: "+m.downloadSource,m.conversion,"SHA-256: "+m.sha256].join("\n")).join("\n\n");
    entries.push({name:"warden-favorites.json",data:JSON.stringify(selection,null,2)+"\n"},{name:"CREDITS.txt",data:credits+"\n"},{name:"README.txt",data:"WARDEN MECH — ASSET SHORTLIST\n\nmodels/ contains the original portable GLBs with embedded textures.\nwarden-favorites.json contains IDs, creator/source/license details, notes and suggested viewer orientation.\nCREDITS.txt records source provenance. Bundled models are CC0 1.0 Universal.\n\nImport each GLB into your game/3D tool. Configure project units, scale, grip, attachment and muzzle points there. Animations are present only when listed in the manifest. No Warden attachment or weapon behavior is configured by this export.\nThe viewer's part filter and wireframe do not modify exported geometry.\n"});
    saveBlob(makeZip(entries),"warden-favorites.zip");$("export-status").textContent="Export ready. Your browser will save the ZIP.";
  } catch(error) {$("export-status").textContent=error.message+" No incomplete ZIP was exported. Retry, or save the JSON shortlist.";}
  finally {exportBusy=false;$("import-json").disabled=false;renderFavorites();}
}
