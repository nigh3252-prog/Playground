async function start() {
  try {
    const response=await fetch("catalog.json");if(!response.ok) throw new Error("Catalog HTTP "+response.status);
    catalog=await response.json();models=catalog.models;byId=new Map(models.map(m=>[m.id,m]));restore();
    $("pack").replaceChildren(new Option("All packs · "+models.length,"all"));
    for(const pack of catalog.packs) $("pack").add(new Option(pack.name+" · "+models.filter(m=>m.pack===pack.id).length,pack.id));
    $("collection-count").textContent=models.length+" MODELS / "+catalog.packs.length+" PACKS";
    initViewer();wireEvents();buildSources();renderCatalog();
    // Small read-only inspection surface used by browser verification and thumbnail generation.
    window.armory={select:selectModel,get models(){return models;},get current(){return current?.id;},get state(){return {favorites:[...favorites],filtered:filtered.map(m=>m.id),loaded:document.body.dataset.ready,meshCount:meshes.length,camera:camera.position.toArray(),target:controls.target.toArray(),renderer:renderer.info.memory};}};
  } catch(error) {
    $("model-name").textContent="Armory unavailable";$("load-status").textContent="Could not start the collection. Reload this page from the Playground site.";
    console.error(error);document.body.dataset.ready="error";
  }
}
